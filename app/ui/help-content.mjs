const textOf = topic => [topic.title,topic.summary,...topic.keywords,...topic.sections.flatMap(section=>[section.title,...section.paragraphs,...(section.steps||[])])].join('\n').normalize('NFKC').toLocaleLowerCase();
export function searchHelpTopics(query='') {
  const tokens=String(query??'').normalize('NFKC').toLocaleLowerCase().trim().split(/\s+/u).filter(Boolean);
  return tokens.length ? helpTopics.filter(topic=>{const text=textOf(topic);return tokens.every(token=>text.includes(token));}) : [...helpTopics];
}
export function getHelpTopic(id) { return helpTopics.find(topic=>topic.id===id)||helpTopics[0]; }
